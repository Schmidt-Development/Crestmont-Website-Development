// Founder decision D3 (2026-10-28): private previews. The gate the runner generates is executed here as the
// Workers runtime would run it (standard Request/Response/WebCrypto), with links signed by the platform's own signer.
import { test } from "node:test";
import assert from "node:assert/strict";
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { previewKey, planGatedPreview, applyGatedPreview, parseJsonc, GATE_FILE } from "../src/preview-gate.ts";
import { previewKey as platformKey, previewSignInUrl, b64url } from "../../src/lib/preview-token.ts";
import { tmp } from "./helpers.ts";

const MASTER = "preview-gate-secret-for-tests-0123456789";
const NAME = "cm-prv-prj-alpha-b0";
const ORIGIN = "https://cm-prv-prj-alpha-b0.acct.workers.dev";
const STARTER = path.join(import.meta.dirname, "..", "starters", "brochure-v1");

type Gate = { fetch(req: Request, env: Record<string, unknown>, ctx?: unknown): Promise<Response> };

function exportOfStarter(): string {
  const dir = tmp("aib-gate-");
  cpSync(STARTER, dir, { recursive: true });
  return dir;
}

async function loadGate(name = NAME): Promise<{ gate: Gate; config: Record<string, unknown>; key: string; dir: string }> {
  const dir = exportOfStarter();
  const key = previewKey(MASTER, name);
  const { plan, problems } = planGatedPreview(dir, name, key);
  assert.deepEqual(problems, []);
  applyGatedPreview(dir, plan!);
  writeFileSync(path.join(dir, "package.json"), JSON.stringify({ type: "module" }));
  const gate = (await import(pathToFileURL(path.join(dir, GATE_FILE)).href)).default as Gate;
  return { gate, config: JSON.parse(readFileSync(path.join(dir, "wrangler.json"), "utf8")), key, dir };
}

/** Stand-in for the static-assets binding: records what it was asked for. */
function assets() {
  const seen: Request[] = [];
  return { seen, binding: { fetch: async (r: Request) => { seen.push(r); return new URL(r.url).pathname === "/missing" ? new Response("not found page", { status: 404 }) : new Response(`<h1>asset ${new URL(r.url).pathname}</h1>`, { headers: { "content-type": "text/html", "cache-control": "public, max-age=3600" } }); } } };
}

async function signIn(gate: Gate, env: Record<string, unknown>, next = "/about.html"): Promise<string> {
  const link = await previewSignInUrl(MASTER, NAME, ORIGIN + "/", { next, audience: "customer" });
  const res = await gate.fetch(new Request(link), env);
  assert.equal(res.status, 302);
  return res.headers.get("set-cookie")!.split(";")[0];
}

test("[AIB-006] D3: the runner and the platform derive the same per-preview key; different previews get different keys", async () => {
  assert.equal(previewKey(MASTER, NAME), await platformKey(MASTER, NAME));
  assert.notEqual(previewKey(MASTER, NAME), previewKey(MASTER, "cm-prv-prj-beta-b0"));
  assert.throws(() => previewKey("short", NAME), /at least 32/);
  await assert.rejects(platformKey("short", NAME), /at least 32/);
});

test("[AIB-006] D3: the deployed config is generated by the runner: gate as entry point for every request, site vars kept, key only for the gate", async () => {
  const { config, key } = await loadGate();
  assert.equal(config.name, NAME);
  assert.equal(config.main, GATE_FILE);
  assert.equal(config.workers_dev, true);
  assert.equal(config.preview_urls, false);
  assert.deepEqual(config.assets, { directory: "./public", binding: "ASSETS", not_found_handling: "404-page", run_worker_first: true });
  assert.deepEqual(config.vars, { CONTACT_MAIL_PROVIDER: "", CRESTMONT_PREVIEW_KEY: key });
  assert.ok(!JSON.stringify(config).includes(MASTER), "the master secret is never deployed");
});

test("[AIB-006] D3: configs a private preview cannot honour are refused, not silently changed", () => {
  const cases: [string, string, RegExp][] = [
    ["wrangler.jsonc", `{ "name": "x", "main": "src/worker.js", "d1_databases": [{ "binding": "DB" }] }`, /does not support: d1_databases/],
    ["wrangler.jsonc", `{ "name": "x", "main": "src/worker.js", "kv_namespaces": [], "services": [] }`, /kv_namespaces, services/],
    ["wrangler.jsonc", `{ "main": "../../etc/x.js" }`, /relative .js/],
    ["wrangler.jsonc", `{ "main": "src/worker.js", "vars": { "CRESTMONT_PREVIEW_KEY": "mine" } }`, /vars.CRESTMONT_PREVIEW_KEY is not allowed/],
    ["wrangler.jsonc", `{ "main": "src/worker.js", "vars": { "X": { "nested": 1 } } }`, /plain value/],
    ["wrangler.jsonc", `{ "assets": { "directory": "/run/secrets" } }`, /relative path/],
    ["wrangler.jsonc", `{ "assets": { "directory": "./public", "binding": "CRESTMONT_PREVIEW_KEY" } }`, /plain identifier/],
    ["wrangler.toml", `name = "x"`, /wrangler.toml is not supported/],
    ["wrangler.jsonc", `{ "name": "x" }`, /nothing to serve/],
    ["wrangler.jsonc", `{ not json`, /could not be read/],
  ];
  for (const [file, text, want] of cases) {
    const dir = tmp("aib-gate-bad-");
    mkdirSync(path.join(dir, "src"), { recursive: true });
    writeFileSync(path.join(dir, "src", "worker.js"), "export default {}");
    writeFileSync(path.join(dir, file), text);
    const r = planGatedPreview(dir, NAME, "k".repeat(43));
    assert.equal(r.plan, null, text);
    assert.match(r.problems.join("; "), want, text);
  }
  // JSONC: comments and trailing commas; a "//" inside a string is data.
  assert.deepEqual(parseJsonc(`{ // c\n "a": "http://x/*y*/", /* b */ "b": [1, 2,], }`), { a: "http://x/*y*/", b: [1, 2] });
});

test("[AIB-006] D3: without a valid session the gate serves nothing (pages, assets, /api/*, gate internals), and fails closed without a key", async () => {
  const { gate, key } = await loadGate();
  const a = assets();
  const env = { ASSETS: a.binding, CRESTMONT_PREVIEW_KEY: key, CONTACT_MAIL_PROVIDER: "" };
  for (const p of ["/", "/index.html", "/assets/css/site.css", "/api/contact", "/robots.txt", "/__crestmont/other", "/__crestmont/auth", "/__crestmont/auth?t=abc.def"]) {
    const res = await gate.fetch(new Request(ORIGIN + p, { method: p.startsWith("/api") ? "POST" : "GET" }), env);
    assert.equal(res.status, 401, p);
    const body = await res.text();
    assert.doesNotMatch(body, /asset|<h1|contact form/i, p);
    assert.equal(res.headers.get("cache-control"), "private, no-store");
    assert.equal(res.headers.get("x-robots-tag"), "noindex, nofollow");
  }
  assert.equal(a.seen.length, 0, "the assets binding was never reached");
  // A forged cookie, a link token used as a cookie, a session for another preview.
  const payload = b64url(new TextEncoder().encode(JSON.stringify({ p: NAME, exp: 9_999_999_999 })));
  for (const cookie of [`__Host-cm_prv=${payload}.AAAA`, `__Host-cm_prv=${new URL(await previewSignInUrl(MASTER, NAME, ORIGIN, { audience: "owner" })).searchParams.get("t")}`]) {
    assert.equal((await gate.fetch(new Request(ORIGIN + "/", { headers: { cookie } }), env)).status, 401, cookie.slice(0, 30));
  }
  const other = await loadGate("cm-prv-prj-beta-b0");
  const betaCookie = await (async () => {
    const link = await previewSignInUrl(MASTER, "cm-prv-prj-beta-b0", "https://cm-prv-prj-beta-b0.acct.workers.dev", { audience: "customer" });
    return (await other.gate.fetch(new Request(link), { ASSETS: a.binding, CRESTMONT_PREVIEW_KEY: other.key })).headers.get("set-cookie")!.split(";")[0];
  })();
  assert.equal((await gate.fetch(new Request(ORIGIN + "/", { headers: { cookie: betaCookie } }), env)).status, 401, "cross-preview session refused");
  const betaLink = await previewSignInUrl(MASTER, "cm-prv-prj-beta-b0", ORIGIN, { audience: "customer" });
  assert.equal((await gate.fetch(new Request(betaLink), env)).status, 401, "a link for another preview is refused");
  // Expired link.
  const old = await previewSignInUrl(MASTER, NAME, ORIGIN, { audience: "owner", now: new Date(Date.now() - 3600_000) });
  assert.equal((await gate.fetch(new Request(old), env)).status, 401, "expired");
  // Tampered payload (same signature).
  const t = new URL(await previewSignInUrl(MASTER, NAME, ORIGIN, { audience: "owner" })).searchParams.get("t")!;
  const forged = b64url(new TextEncoder().encode(JSON.stringify({ p: NAME, exp: 9_999_999_999, n: "/" }))) + "." + t.split(".")[1];
  assert.equal((await gate.fetch(new Request(`${ORIGIN}/__crestmont/auth?t=${forged}`), env)).status, 401, "tampered");
  // No key configured: nothing is served, even with a valid-looking session.
  const cookie = await signIn(gate, env);
  assert.equal((await gate.fetch(new Request(ORIGIN + "/", { headers: { cookie } }), { ASSETS: a.binding })).status, 401);
});

test("[AIB-006] D3: a platform-signed link becomes a host-only session; the site then works, without ever seeing the key or the session cookie", async () => {
  const { gate, key } = await loadGate();
  const a = assets();
  const env = { ASSETS: a.binding, CRESTMONT_PREVIEW_KEY: key, CONTACT_MAIL_PROVIDER: "" };
  const link = await previewSignInUrl(MASTER, NAME, ORIGIN + "/whatever", { next: "/about.html", audience: "customer" });
  assert.ok(link.startsWith(`${ORIGIN}/__crestmont/auth?t=`));
  const res = await gate.fetch(new Request(link), env);
  assert.equal(res.status, 302);
  assert.equal(res.headers.get("location"), "/about.html", "relative redirect; the token leaves the address bar");
  const sc = res.headers.get("set-cookie")!;
  assert.match(sc, /^__Host-cm_prv=[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+; Path=\/; Secure; HttpOnly; SameSite=Lax; Max-Age=7200$/);
  assert.equal(res.headers.get("referrer-policy"), "no-referrer");
  const cookie = sc.split(";")[0];

  const page = await gate.fetch(new Request(ORIGIN + "/about.html", { headers: { cookie: `${cookie}; theme=dark` } }), env);
  assert.equal(page.status, 200);
  assert.match(await page.text(), /asset \/about.html/);
  assert.equal(page.headers.get("cache-control"), "private, no-store", "never cached publicly");
  assert.equal(a.seen.at(-1)!.headers.get("cookie"), "theme=dark", "the gate cookie is not passed on");
  // /api/* runs the site's own Worker (starter: run_worker_first ["/api/*"]) with an env that has no key.
  const api = await gate.fetch(new Request(ORIGIN + "/api/contact", { method: "POST", headers: { cookie }, body: new URLSearchParams({ name: "Pat", email: "pat@example.com", message: "Hi" }) }), env);
  assert.equal(api.status, 503);
  assert.match(await api.text(), /not connected yet/);
  assert.equal(api.headers.get("x-robots-tag"), "noindex, nofollow");

  // Open redirects: the platform only signs relative paths, and the gate re-checks.
  assert.equal(new URL(await previewSignInUrl(MASTER, NAME, ORIGIN, { next: "//evil.example/x", audience: "owner" })).origin, ORIGIN);
  const evil = await gate.fetch(new Request(await previewSignInUrl(MASTER, NAME, ORIGIN, { next: "//evil.example/x", audience: "owner" })), env);
  assert.equal(evil.headers.get("location"), "/");
  const enc = new TextEncoder();
  const payload = b64url(enc.encode(JSON.stringify({ p: NAME, exp: Math.floor(Date.now() / 1000) + 60, n: "/\\evil.example" })));
  const k = await crypto.subtle.importKey("raw", enc.encode(key), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const sig = b64url(new Uint8Array(await crypto.subtle.sign("HMAC", k, enc.encode(`link.${payload}`))));
  assert.equal((await gate.fetch(new Request(`${ORIGIN}/__crestmont/auth?t=${payload}.${sig}`), env)).headers.get("location"), "/");
});
